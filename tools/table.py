"""Regenerates the kelvin -> overlay lookup table in ColorMath.kt.

An overlay can't multiply the screen by a color; it can only alpha-blend on top:
    out = src * (1 - a) + C * a
So for each color temperature we search for the (a, C) that best matches the
ideal "multiply by the blackbody color" result, measured in perceptual
lightness, while capping how much it lifts black (so dark scenes stay dark).

Run:  python3 tools/table.py   and paste the output into ColorMath.TABLE.
"""
import math

P = 0.733      # code value -> perceived lightness exponent (~ (v^2.2)^(1/3))
CAP = 0.15     # max black lift per channel, in code values (~2% luminance)
S = [i / 80 for i in range(81)]


def kelvin_rgb(K):  # Tanner Helland's blackbody fit, 0..255
    t = K / 100
    r = 255 if t <= 66 else 329.698727446 * (t - 60) ** -0.1332047592
    g = (99.4708025861 * math.log(t) - 161.1195681661) if t <= 66 else 288.1221695283 * (t - 60) ** -0.0755148492
    b = 255 if t >= 66 else (0 if t <= 19 else 138.5177312231 * math.log(t - 10) - 305.0447927307)
    return [min(255, max(0, x)) for x in (r, g, b)]


WHITE = kelvin_rgb(6500)


def gains(K):
    return [min(1, c / w) for c, w in zip(kelvin_rgb(K), WHITE)]


def err(a, c, kc):
    return sum(((s * (1 - a) + a * c) ** P - (s * kc) ** P) ** 2 for s in S)


print("    // kelvin, alpha, r, g, b  (generated by tools/table.py)")
for K in range(1000, 6600, 100):
    k = gains(K)
    best = None
    for i in range(0, 191):
        a = i / 200
        tot, C = 0, []
        for kc in k:
            cands = [j / 100 for j in range(101) if a * j / 100 <= CAP + 1e-9]
            be = min((err(a, c, kc), c) for c in cands[::5])
            fine = [c for c in cands if be[1] - 0.05 <= c <= be[1] + 0.05]
            be = min((err(a, c, kc), c) for c in fine)
            tot += be[0]
            C.append(be[1])
        if best is None or tot < best[0]:
            best = (tot, a, C)
    print("        doubleArrayOf(%d.0, %.3f, %.2f, %.2f, %.2f)," % (K, best[1], *best[2]))
